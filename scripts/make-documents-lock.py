"""Build omarchy/locks/documents.lock: the Office/PDF libraries for jarvis/capabilities/documents.py.

    uv pip compile omarchy/locks/documents.in -c constraints.txt --python-version 3.14 \
        --python-platform x86_64-manylinux_2_28 --generate-hashes --no-header -o full.lock
    python scripts/make-documents-lock.py full.lock > omarchy/locks/documents.lock

constraints.txt holds the exact pins of local-speech.lock and pipecat.lock (`--constraints`), so shared
packages (Pillow, typing-extensions…) resolve to the versions those locks install; those are then left
out here and installed by their own lock, with their own hashes.
"""

import re
import sys
from pathlib import Path

repo = Path(__file__).resolve().parents[1]
pinned: dict[str, str] = {}
for lock in ("local-speech.lock", "pipecat.lock"):
    for m in re.finditer(r"^([A-Za-z0-9_.-]+)==(\S+)", (repo / "omarchy/locks" / lock).read_text(), re.M):
        pinned[m.group(1).lower()] = m.group(2)

if len(sys.argv) > 1 and sys.argv[1] == "--constraints":
    print("\n".join(f"{k}=={v}" for k, v in sorted(pinned.items())))
    sys.exit(0)

blocks, current = [], []
for line in Path(sys.argv[1]).read_text().splitlines():
    if re.match(r"^[A-Za-z0-9_.-]+==", line):
        if current:
            blocks.append(current)
        current = [line]
    elif current and line.startswith(" "):
        current.append(line)
if current:
    blocks.append(current)

print("# Office and PDF libraries for jarvis/capabilities/documents.py, with hashes (Linux x86_64, Python 3.14).")
print("# Installed with --require-hashes --no-deps after the speech and Pipecat locks; packages they already pin")
print("# identically (Pillow, typing-extensions, ...) are omitted. Generated by scripts/make-documents-lock.py.")
print("# python-docx, python-pptx, openpyxl, XlsxWriter, et-xmlfile: MIT; pypdf: BSD-3; fpdf2: LGPL-3.0;")
print("# lxml: BSD-3; fonttools: MIT; defusedxml: PSF-2.0.")
kept = 0
for block in blocks:
    name, version = block[0].split("==")[0].lower(), block[0].split("==")[1].split()[0]
    if pinned.get(name) == version:
        continue
    kept += 1
    print("\n".join(line for line in block if not line.strip().startswith("# via") and not line.strip().startswith("#   ")))
print(f"# {kept} packages", file=sys.stderr)
