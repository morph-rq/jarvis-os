"""Build omarchy/locks/pipecat.lock: Pipecat and what it needs beyond the local speech lock.

    uv pip compile req.in -c <speech pins minus protobuf/websockets> --python-version 3.14 \
        --python-platform x86_64-manylinux_2_28 --generate-hashes --no-header -o full.lock
    python scripts/make-pipecat-lock.py full.lock > omarchy/locks/pipecat.lock

Packages the speech lock already pins at the same version are left out (installed by it, with its
hashes); the rest, including the two deliberate overrides, stay with their hashes.
"""

import re
import sys
from pathlib import Path

repo = Path(__file__).resolve().parents[1]
speech = {m.group(1).lower(): m.group(2) for m in re.finditer(r"^([A-Za-z0-9_.-]+)==(\S+)", (repo / "omarchy/locks/local-speech.lock").read_text(), re.M)}
blocks, current = [], []
for line in Path(sys.argv[1]).read_text().splitlines():
    if re.match(r"^[A-Za-z0-9_.-]+==", line):
        if current:
            blocks.append(current)
        current = [line]
    elif current and line.startswith(" "):
        current.append(line)
if current:
    blocks.append(current)

print("# Pipecat 1.13.0 (https://github.com/pipecat-ai/pipecat, BSD-2-Clause) for jarvisd's voice engine, with hashes.")
print("# Installed after locks/local-speech.lock with --require-hashes --no-deps (Linux x86_64, Python 3.14).")
print("# Generated by scripts/make-pipecat-lock.py; packages that lock already pins identically are omitted.")
print("# Deliberate overrides of the speech lock: protobuf 6.x (Pipecat needs <7; onnxruntime accepts 6.x)")
print("# and websockets 16.x (google-genai >= 2.25 needs <17).")
kept = 0
for block in blocks:
    name, version = block[0].split("==")[0].lower(), block[0].split("==")[1].split()[0]
    if speech.get(name) == version:
        continue
    kept += 1
    print("\n".join(line for line in block if not line.strip().startswith("# via") and not line.strip().startswith("#   ")))
print(f"# {kept} packages", file=sys.stderr)
