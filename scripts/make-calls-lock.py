"""Build omarchy/locks/calls.lock: WebRTC media for WhatsApp calls (aiortc), layered on the speech and Pipecat locks.

    uv pip compile omarchy/locks/calls.in -c <pins of local-speech.lock + pipecat.lock + documents.lock> \
        --override <(echo av==18.1.0) --python-version 3.14 --python-platform x86_64-manylinux_2_28 \
        --generate-hashes --no-header -o full.lock
    python scripts/make-calls-lock.py full.lock > omarchy/locks/calls.lock

Override: aiortc 1.15.0 declares av<18, while the speech lock pins av 18.1.0 (faster-whisper). Opus
negotiation and two-way audio with exactly this pair were verified in the Omarchy VM (DTLS sha-256,
both directions carrying signal), so the speech lock is left unchanged and aiortc is installed with
--no-deps. Packages an earlier lock already pins at the same version are omitted.
"""

import re
import sys
from pathlib import Path

repo = Path(__file__).resolve().parents[1]
pinned: dict[str, str] = {}
for lock in ("local-speech.lock", "pipecat.lock", "documents.lock"):
    for m in re.finditer(r"^([A-Za-z0-9_.-]+)==(\S+)", (repo / "omarchy/locks" / lock).read_text(), re.M):
        pinned.setdefault(m.group(1).lower(), m.group(2))
blocks, current = [], []
for line in Path(sys.argv[1]).read_text().splitlines():
    if re.match(r"^[A-Za-z0-9_.-]+==", line):
        if current:
            blocks.append(current)
        current = [line]
    elif current and line.startswith(" ") and not line.strip().startswith("#"):
        current.append(line)
if current:
    blocks.append(current)

print("# WebRTC media for WhatsApp calls: aiortc 1.15.0 (BSD-3-Clause) and its dependencies, with hashes.")
print("# Installed after locks/local-speech.lock and locks/pipecat.lock with --require-hashes --no-deps")
print("# (Linux x86_64, Python 3.14). Generated by scripts/make-calls-lock.py; av stays at the speech lock's 18.1.0.")
for block in blocks:
    name, version = block[0].split("==", 1)
    version = version.split()[0]
    if pinned.get(name.lower()) == version:
        continue
    print("\n".join(block).rstrip(" \\"))
