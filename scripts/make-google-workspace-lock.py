"""Build omarchy/locks/google-workspace.lock: taylorwilsdon/google_workspace_mcp (workspace-mcp, MIT)
and its dependencies, for its own virtual environment (~/.local/share/jarvis-workos/venvs/google-workspace).

    uv pip compile omarchy/locks/google-workspace.in --python-version 3.14 \
        --python-platform x86_64-manylinux_2_28 --generate-hashes --no-header --only-binary :all: -o full.lock
    python scripts/make-google-workspace-lock.py full.lock > omarchy/locks/google-workspace.lock

It lives in a separate venv because it installs top-level packages named auth, core, gmail… that
would collide with other code, and it pins its own FastMCP/Starlette stack.
"""

import re
import sys
from pathlib import Path

lines = Path(sys.argv[1]).read_text(encoding="utf-8").splitlines()
kept = [line for line in lines if not line.lstrip().startswith("#")]
count = sum(1 for line in kept if re.match(r"^[A-Za-z0-9_.-]+==", line))
print("# Google Workspace MCP server (workspace-mcp, MIT) with hashes (Linux x86_64, Python 3.14), for its own venv.")
print("# Installed with --require-hashes --no-deps --only-binary :all:. Generated by scripts/make-google-workspace-lock.py.")
print("\n".join(kept))
print(f"# {count} packages", file=sys.stderr)
